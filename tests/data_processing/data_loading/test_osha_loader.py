def test_load_genduty_sample_naics_filter(enforcement_loader):
    """Test that general duty sample filters by NAICS 325/324 and keywords."""
    df = enforcement_loader.load_genduty_sample()

    assert isinstance(df, pd.DataFrame)
    assert len(df) > 0
    # All results should either have NAICS 325/324 or contain process safety keywords
    for _, row in df.iterrows():
        naics = str(row.get("naics_code", ""))
        text = str(row.get("text", "")).lower()
        naics_match = naics.startswith("325") or naics.startswith("324")
        keyword_match = any(
            kw in text
            for kw in ["chemical", "reactive", "explosion", "release", "toxic", "process safety"]
        )
        assert naics_match or keyword_match, (
            f"Row should match NAICS or keyword filter: naics={naics}"
        )


